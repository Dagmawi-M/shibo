const BATTERY = (summary: string, tags: string[], volts: string, specs: string[]): PartInfo => ({
  summary, tags: ['battery', 'power', 'supply', 'cell', ...tags], volts, specs,
  pins: { '+': 'Positive terminal', '-': 'Negative terminal' },
});

const REG = (summary: string, tags: string[], volts: string, specs: string[]): PartInfo => ({
  summary, tags: ['regulator', 'voltage regulator', 'ldo', 'power', 'supply', ...tags], volts, specs,
  pins: { IN: 'Unregulated input', GND: 'Ground', OUT: 'Regulated output' },
});

